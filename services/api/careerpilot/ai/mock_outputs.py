"""Deterministic outputs for MockLLMProvider (development/tests only).

Each handler returns JSON matching the request schema. Handlers use only `request.context`, mirroring how a
real model would only see the prompt content.
"""

from __future__ import annotations

import re
from typing import Any

from careerpilot.ai.heuristics import heuristic_extract
from careerpilot.ai.providers import LLMRequest
from careerpilot.ai.schemas import COVER_LETTER_SCHEMA_VERSION, JOB_SCHEMA_VERSION
from careerpilot.ai.skills import static_normalizer

_PREFERRED_MARKERS = re.compile(r"(nice to have|preferred|bonus|a plus|desirable|good to have)", re.I)
_YEARS = re.compile(r"(\d{1,2})\s*\+?\s*(?:-|to)?\s*(\d{1,2})?\s*\+?\s*years", re.I)


def resume_extraction(request: LLMRequest) -> dict[str, Any]:
    return heuristic_extract(request.context["text"], static_normalizer()).model_dump()


def job_extraction(request: LLMRequest) -> dict[str, Any]:
    text: str = request.context["text"]
    normalizer = static_normalizer()
    required: list[str] = []
    preferred: list[str] = []
    in_preferred_block = False
    for line in text.splitlines():
        if _PREFERRED_MARKERS.search(line):
            in_preferred_block = True
        elif re.search(r"(requirements|required|must have|qualifications)", line, re.I):
            in_preferred_block = False
        for m in normalizer.find_in_text(line):
            target = preferred if in_preferred_block or _PREFERRED_MARKERS.search(line) else required
            if m.canonical not in required and m.canonical not in preferred:
                target.append(m.canonical)
    min_years = max_years = None
    if m2 := _YEARS.search(text):
        min_years = float(m2.group(1))
        max_years = float(m2.group(2)) if m2.group(2) else None
    lowered = text.lower()
    arrangement = "remote" if "remote" in lowered else "hybrid" if "hybrid" in lowered else None
    employment = (
        "contract"
        if "contract" in lowered
        else "part_time"
        if "part-time" in lowered
        else "internship"
        if "intern" in lowered
        else "full_time"
        if "full-time" in lowered or "full time" in lowered
        else None
    )
    bullets = [ln.strip("•*- ").strip() for ln in text.splitlines() if ln.strip().startswith(("-", "•", "*"))]
    return {
        "schema_version": JOB_SCHEMA_VERSION,
        "title": None,
        "required_skills": required,
        "preferred_skills": preferred,
        "min_experience_years": min_years,
        "max_experience_years": max_years,
        "education_requirement": None,
        "employment_type": employment,
        "work_arrangement": arrangement,
        "responsibilities": bullets[:15],
        "benefits": [],
        "warnings": ["Generated by the deterministic mock provider; review every field."],
    }


def cover_letter(request: LLMRequest) -> dict[str, Any]:
    facts: dict[str, Any] = request.context["candidate_facts"]
    job: dict[str, Any] = request.context["job"]
    matched = [
        s
        for s in facts.get("skills", [])
        if s in set(job.get("required_skills", [])) | set(job.get("preferred_skills", []))
    ]
    latest = (facts.get("experiences") or [None])[0]
    used: list[str] = []
    paragraphs = [f"Dear {job.get('company', 'Hiring')} team,"]
    opener = (
        f"I am writing to apply for the {job.get('title', 'open')} position at {job.get('company', 'your company')}."
    )
    if latest:
        opener += (
            f" I currently work as {latest['title']} at {latest['company']}."
            if latest.get("is_current")
            else f" Most recently, I worked as {latest['title']} at {latest['company']}."
        )
        used.append(f"experience: {latest['title']} at {latest['company']}")
    paragraphs.append(opener)
    if matched:
        paragraphs.append(
            "My background includes hands-on work with "
            + ", ".join(matched[:6])
            + ", which align with the skills listed for this role."
        )
        used += [f"skill: {s}" for s in matched[:6]]
    if facts.get("summary"):
        paragraphs.append(str(facts["summary"])[:400])
        used.append("summary")
    paragraphs.append(
        "I would welcome the opportunity to discuss how I can contribute to your team. "
        "Thank you for your time and consideration."
    )
    paragraphs.append(f"Sincerely,\n{facts.get('name', '')}".strip())
    return {"schema_version": COVER_LETTER_SCHEMA_VERSION, "letter": "\n\n".join(paragraphs), "facts_used": used}
